def load_pinyin_order():
    """从外部 label.txt 读取拼音顺序(与 ORIG_NAMES 一一对应)。"""
    lp = os.path.join(PROJECT_ROOT, "data", "external", "cls_chinese_medicine", "label.txt")
    pys = []
    with open(lp, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) >= 2:
                pys.append(parts[1])
    return pys


def build():
    labels = load_labels()
    assert set(labels.keys()) == set(ORIG_NAMES), "ORIG_NAMES 与 label2idx 不一致!"

    pinyins = load_pinyin_order()
    assert len(pinyins) == len(ORIG_NAMES), "pinyin 数量与 ORIG_NAMES 不一致!"

    # 异形饮片统一为通用节点名(与 kg_builder._normalize_name 保持一致)
    ALIAS = {
        "枸杞子": "枸杞", "北沙参块": "北沙参", "北沙参条": "北沙参",
        "天麻块": "天麻", "天麻片": "天麻", "肉苁蓉根": "肉苁蓉",
        "肉苁蓉片": "肉苁蓉", "枳壳片": "枳壳", "枳壳条": "枳壳",
        "首乌藤块": "首乌藤", "首乌藤片": "首乌藤", "玉竹条": "玉竹",
        "玉竹片": "玉竹", "人参切片": "人参", "野菊花": "菊花",
    }

    herbs_rows = []
    props_rows = []
    missing = []
    for orig, pinyin in zip(ORIG_NAMES, pinyins):
        node_name = ALIAS.get(orig, orig)
        if orig in HERB_DATA:
            prop, mer, func, paired = HERB_DATA[orig]
        else:
            missing.append(orig)
            prop, mer, func, paired = "", "", "", ""
        herbs_rows.append({
            "name": node_name,
            "property": prop,
            "meridian": mer,
            "function": func,
            "paired_herb": paired,
        })
        # property_text 供多模态训练: 组合成自然语言
        if prop or mer or func:
            prop_text = f"性味{prop}；归{mer}经；功效：{func}。"
        else:
            prop_text = ""
        props_rows.append({
            "pinyin": pinyin,
            "chinese_name": node_name,
            "property_text": prop_text,
        })

    # 额外知识节点(配伍/相似药引用, 非训练集)
    for name, (prop, mer, func, paired) in EXTRA_HERBS.items():
        herbs_rows.append({
            "name": name,
            "property": prop,
            "meridian": mer,
            "function": func,
            "paired_herb": paired,
        })

    # 写出 herbs.csv
    with open(HERBS_OUT, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["name", "property", "meridian", "function", "paired_herb"])
        w.writeheader()
        w.writerows(herbs_rows)

    # 写出 herb_properties.csv (保留原表头顺序)
    with open(PROPS_OUT, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["pinyin", "chinese_name", "property_text"])
        w.writeheader()
        w.writerows(props_rows)

    print(f"[done] 写入 {len(herbs_rows)} 条 -> herbs.csv")
    print(f"[done] 写入 {len(props_rows)} 条 -> herb_properties.csv")
    if missing:
        print(f"[warn] 缺失药性数据 {len(missing)} 味: {missing}")
    else:
        print("[ok] 163 味药药性数据全部就绪")


if __name__ == "__main__":
    build()
