def get_confusable(name: str):
    """返回药材 name 的易混淆鉴别信息（dict），无则返回 None。

    支持双向查询：传入对中任意一方均返回同一条目（以数据表内存在的药材为主）。
    """
    entry = CONFUSABLE_HERBS.get(name)
    if entry:
        return dict(entry)
    for peer, e in CONFUSABLE_HERBS.items():
        if e.get("peer") == name:
            return dict(e, peer=peer)
    return None
